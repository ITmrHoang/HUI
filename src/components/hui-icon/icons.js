/** Lấy nội dung SVG của icon theo tên (undefined nếu chưa đăng ký) */
export function getIcon(name) {
  return registry.get(name);
}

/** Danh sách tên icon đã đăng ký (dùng cho Storybook / tài liệu) */
export function getIconNames() {
  return [...registry.keys()];
}

/**
 * Đăng ký (hoặc ghi đè) icon. `svgContent` là phần bên trong <svg viewBox="0 0 24 24">.
 * Chỉ truyền SVG do chính dự án của bạn cung cấp — nội dung được chèn thẳng vào DOM.
 * Các <hui-icon> đang hiển thị icon trùng tên sẽ tự vẽ lại.
 */
export function registerIcon(name, svgContent) {
  registry.set(name, svgContent);
  document.dispatchEvent(new CustomEvent('hui-icon-registered', { detail: { name } }));
}
